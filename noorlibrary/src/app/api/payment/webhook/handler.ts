// src/app/api/payment/webhook/handler.ts
// Paystack webhook endpoint.
// Listens for charge.success events to guarantee payment grants even when users
// pay via bank transfers, USSD, or suffer network drops before client redirects.
// Includes multi-project prefix filtering and optional webhook multiplexing.

import { NextRequest, NextResponse } from 'next/server';
import crypto from 'crypto';
import { adminDb } from '../../../../lib/firebase-admin';
import { grantAccess } from '../../../../lib/payment-grants';
import { FieldValue } from 'firebase-admin/firestore';

export async function POST(request: NextRequest) {
  try {
    const rawBody = await request.text();
    const signature = request.headers.get('x-paystack-signature');
    const secretKey = process.env.PAYSTACK_SECRET_KEY || '';

    if (!secretKey) {
      console.error('PAYSTACK_SECRET_KEY is not defined in environment variables.');
      return NextResponse.json({ error: 'Server misconfigured' }, { status: 500 });
    }

    if (!signature) {
      return NextResponse.json({ error: 'Missing Paystack signature' }, { status: 400 });
    }

    // Verify HMAC-SHA512 signature
    const hash = crypto
      .createHmac('sha512', secretKey)
      .update(rawBody)
      .digest('hex');

    if (hash !== signature) {
      console.warn('Paystack webhook received with invalid signature.');
      return NextResponse.json({ error: 'Invalid signature' }, { status: 401 });
    }

    const payload = JSON.parse(rawBody);
    const { event, data } = payload;
    const reference = String(data?.reference || '');

    // Multi-project Paystack safety:
    // Only process transactions generated by Noor Library (starts with noor-, legacy noor_, or NL_).
    const isNoorTx = reference.startsWith('noor-') || reference.startsWith('noor_') || reference.startsWith('NL_');

    if (!isNoorTx) {
      console.log(`[Paystack Webhook] Non-Noor transaction ${reference || 'unknown'} ignored safely.`);

      // Optional Webhook Multiplexing: Forward to secondary project webhook if configured
      const forwardUrl = process.env.PAYSTACK_FORWARD_WEBHOOK_URL;
      if (forwardUrl) {
        try {
          await fetch(forwardUrl, {
            method: 'POST',
            headers: {
              'Content-Type': 'application/json',
              'x-paystack-signature': signature,
            },
            body: rawBody,
          });
          console.log(`[Paystack Webhook] Forwarded non-Noor event (${event}, ref: ${reference}) to ${forwardUrl}`);
        } catch (fwdErr) {
          console.error(`[Paystack Webhook] Failed to forward to ${forwardUrl}:`, fwdErr);
        }
      }

      return NextResponse.json(
        { received: true, ignored: true, reason: 'Non-Noor transaction' },
        { status: 200 }
      );
    }

    if (event === 'charge.success' && data && data.status === 'success') {
      const metadata = (data.metadata || {}) as Record<string, any>;
      const customFields = Array.isArray(metadata.custom_fields) ? metadata.custom_fields : [];
      
      const getCustomField = (varName: string): string => {
        const found = customFields.find((f: any) => f?.variable_name === varName);
        return found?.value ? String(found.value) : '';
      };

      const resolvedUid = metadata.uid || getCustomField('uid') || 'anonymous';
      const rawType = metadata.type || metadata.item_type || getCustomField('item_type') || 'read';
      const resolvedType = rawType === 'book' ? 'read' : rawType;
      
      const resolvedItemId = metadata.itemId || metadata.bookId || metadata.courseId || metadata.seriesId || getCustomField('item_id');

      await grantAccess({
        reference,
        uid: resolvedUid,
        type: resolvedType,
        paystackResult: {
          status: true,
          message: 'Webhook charge verified',
          data,
        },
        bookId: metadata.bookId || (resolvedType === 'read' || resolvedType === 'download' ? resolvedItemId : undefined),
        seriesId: metadata.seriesId || (resolvedType === 'series' ? resolvedItemId : undefined),
        courseId: metadata.courseId || (resolvedType === 'course' ? resolvedItemId : undefined),
        email: data.customer?.email || metadata.email,
        currency: data.currency || 'NGN',
        message: metadata.message,
        outreachTitle: metadata.outreachTitle,
        outreachMessage: metadata.outreachMessage,
        outreachTarget: metadata.outreachTarget,
        outreachContentId: metadata.outreachContentId,
      });

      console.log(`[Paystack Webhook] Successfully processed and granted access for ${reference}`);
    }

    return NextResponse.json({ received: true }, { status: 200 });
  } catch (err: any) {
    console.error('[Paystack Webhook Error]:', err);
    try {
      await adminDb.collection('failed_grants').add({
        type: 'webhook_failure',
        error: err?.message || String(err),
        createdAt: FieldValue.serverTimestamp(),
      });
    } catch {}
    // Return 200 to acknowledge webhook receipt so Paystack does not retry endlessly on logic errors
    return NextResponse.json({ received: true, error: err?.message }, { status: 200 });
  }
}
